/*=============================================================================
 *  Ring Buffer 参数
 *============================================================================*/

/**
 * ring buffer 单条记录最大尺寸
 * 
 * 限制原因：
 * - eBPF verifier 要求采样长度有编译期上界
 * - 内核 array-map value_size 上限 32KB
 * 
 * 实际需求：
 * - veth MTU 1500 → 最大 TCP 负载 1460
 * - 2048 有富余
 */
#ifndef MAX_REC
#define MAX_REC      2048
#endif

/**
 * ring buffer 总容量（4MB）
 */
#ifndef RING_SIZE
#define RING_SIZE    (4 << 20)
#endif

/**
 * 重传缓存槽位数
 * seq % CACHE_SLOTS 索引
 */
#ifndef CACHE_SLOTS
#define CACHE_SLOTS  1024
#endif

/*=============================================================================
 *  Ring 记录类型
 *============================================================================*/

#define MIRROR_CLIENT  0           /* 客户端 TCP 负载（镜像数据） */
#define MIRROR_CTRL    1           /* 从机方向完整以太网帧（ACK/应答） */

/*=============================================================================
 *  Ring 记录结构
 *  
 *  8 字节定长头 + 变长数据（负载/整帧）
 *  len 字段为宿主字节序（BPF 与 host 同为 x86 小端）
 *============================================================================*/

struct mirror_rec {
    unsigned char  type;           /* MIRROR_CLIENT / MIRROR_CTRL */
    unsigned char  rsv[3];         /* 对齐（4 字节边界） */
    unsigned int   len;            /* 变长部分字节数 */
};

