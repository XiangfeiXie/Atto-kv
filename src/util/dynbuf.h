/*=============================================================================
 *  dynbuf.h — 轻量级动态缓冲区
 *  
 *  功能：提供简单、高效的动态字节缓冲区
 *  
 *  设计特点：
 *  1. 单次连续内存分配
 *  2. len/cap 管理
 *  3. 自动扩容
 *  4. 适合网络 I/O 缓冲场景
 *  
 *  使用场景：
 *  - 读缓冲（协议解析）
 *  - 写缓冲（响应构建）
 *  - RESP 序列化
 *============================================================================*/

#ifndef __DYN_BUF_H__
#define __DYN_BUF_H__

/*=============================================================================
 *  DynBuf 缓冲区大小参数
 *  
 *  原 net_common.h 的内容，net_common.h 已删除
 *  这两个是 DynBuf 库自身的尺寸参数
 *  
 *  设计考虑：
 *  - INIT：连接缓冲的初始分配大小
 *  - MAX：dynbuf_reserve 的硬增长上限
 *  
 *  网络引擎与 ntyco 都通过 dynbuf_init 以 INIT 初始化连接缓冲
 *  故归位于 dynbuf 自身
 *============================================================================*/

/**
 * 初始缓冲区大小（64KB）
 * 
 * 每个连接第一次分配时的大小
 * 64KB 对大多数网络命令足够，减少频繁扩容
 * 
 * 如果命令大于 64KB，会自动扩容
 */
#define KVS_NET_BUF_INIT  65536

/**
 * 缓冲区最大大小（16MB）
 * 
 * dynbuf_reserve 的硬增长上限
 * 防止恶意客户端发送超大命令导致内存耗尽
 * 
 * 超过此限制的写入会失败（返回 -1）
 */
#ifndef KVS_NET_BUF_MAX
#define KVS_NET_BUF_MAX   (16 * 1024 * 1024)  /* 16 MB */
#endif

/*=============================================================================
 *  动态缓冲区结构
 *============================================================================*/

/**
 * DynBuf 结构
 * 
 * 内存布局：
 *  +---------+---------+---------------------------+
 *  |  len     |  cap    |  buf (动态分配)           |
 *  +---------+---------+---------------------------+
 *  | 已使用   | 总容量   | 实际数据                  |
 *  +---------+---------+---------------------------+
 *  
 *  - buf：指向堆内存的指针
 *  - len：当前已使用的字节数（有效数据长度）
 *  - cap：当前已分配的容量（buf 的总大小）
 * 
 * 保证：0 <= len <= cap
 *       需要写入时 len 可能小于 cap，有剩余空间
 */
typedef struct {
    char *buf;   /* 数据缓冲区指针（堆内存） */
    int   len;   /* 当前有效数据长度（字节数） */
    int   cap;   /* 缓冲区总容量（字节数） */
} DynBuf;

/*=============================================================================
 *  API 函数
 *============================================================================*/

/**
 * 初始化动态缓冲区
 * 
 * @param db 动态缓冲区指针
 * @param init_cap 初始容量（推荐 KVS_NET_BUF_INIT）
 * 
 * 行为：
 * - 分配 init_cap 字节的内存
 * - 设置 len = 0, cap = init_cap
 * 
 * 注意：
 * - 如果 init_cap <= 0，使用 KVS_NET_BUF_INIT
 * - 调用者负责调用 dynbuf_free 释放内存
 */
void dynbuf_init(DynBuf *db, int init_cap);

/**
 * 保留/扩容缓冲区
 * 
 * @param db 动态缓冲区指针
 * @param total_cap 需要的总容量
 * @return 0 成功，-1 失败（超过 KVS_NET_BUF_MAX 或内存不足）
 * 
 * 行为：
 * - 如果 total_cap <= 当前 cap，直接返回
 * - 否则扩容到 total_cap（或更大）
 * - 保留原有数据
 * 
 * 扩容策略：
 * - 至少为 total_cap
 * - 不超过 KVS_NET_BUF_MAX
 * 
 * 调用场景：
 * - 需要写入大量数据前预分配
 * - reply_integer/reply_bulk 中一次 reserve 多次写入
 */
int dynbuf_reserve(DynBuf *db, int total_cap);

/**
 * 追加数据到缓冲区
 * 
 * @param db 动态缓冲区指针
 * @param data 待追加的数据指针
 * @param len 待追加的数据长度
 * @return 0 成功，-1 失败（内存不足）
 * 
 * 行为：
 * - 如果空间不足，自动扩容
 * - 追加到当前 len 之后
 * - 更新 len
 * 
 * 性能优化：
 * - 调用前可用 dynbuf_reserve 预分配
 * - 连续多次 cat 只需一次扩容
 */
int dynbuf_cat(DynBuf *db, const char *data, int len);

/**
 * 清空缓冲区
 * 
 * @param db 动态缓冲区指针
 * 
 * 行为：
 * - 设置 len = 0
 * - 不释放内存（保留 cap）
 * - 下次写入直接覆盖
 * 
 * 优点：
 * - 避免频繁分配/释放
 * - 适合连接复用场景（Slab 风格）
 */
void dynbuf_clear(DynBuf *db);

/**
 * 释放缓冲区内存
 * 
 * @param db 动态缓冲区指针
 * 
 * 行为：
 * - 释放 buf 指向的堆内存
 * - 设置 buf = NULL, len = 0, cap = 0
 * 
 * 调用时机：
 * - 连接关闭时释放缓冲
 * - 程序退出时清理资源
 */
void dynbuf_free(DynBuf *db);

/*=============================================================================
 *  辅助宏
 *============================================================================*/

/**
 * 追加字符串字面量到缓冲区
 * 
 * @param wb 动态缓冲区指针
 * @param s 字符串字面量（如 "OK\r\n"）
 * 
 * 示例：
 *   dynbuf_lit(wb, "+OK\r\n");
 * 
 * 等价于：
 *   dynbuf_cat(wb, "+OK\r\n", 5);
 * 
 * 优点：
 * - 自动计算长度（编译期）
 * - 更简洁的语法
 * - 避免运行时 strlen
 */
#define dynbuf_lit(wb, s) dynbuf_cat((wb), "" s, (int)(sizeof(s) - 1))

#endif /* __DYN_BUF_H__ */