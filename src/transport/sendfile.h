/*=============================================================================
 *  sendfile.h — sendfile（TCP 零拷贝）传输方式
 *  
 *  功能：基于 Linux sendfile 系统调用的全量同步传输实现
 *  
 *  设计原则：
 *  1. 零拷贝：数据从内核直接发送到 socket，绕过用户态
 *  2. 服务端/客户端都在本文件实现（sendfile.c）
 *  3. 由 repl_fullsync.c 按配置开关直接调用
 *  
 *  适用场景：本地网络或低延迟要求不高的环境
 *  优势：实现简单，兼容性好，无需特殊硬件
 *============================================================================*/

#ifndef __SENDFILE_H__
#define __SENDFILE_H__

#include <stdint.h>

/*=============================================================================
 *  传输参数
 *============================================================================*/

/* 客户端接收缓冲大小 = 快照硬上限（整份快照必须先收进这块缓冲才能就地加载）。
 * 与 RDMA 的 RDMA_BUF_SIZE 目前同值，但两条路各自独立定义 ——
 * 缓冲尺寸没有必须相等的理由，之后要分开调就直接改这里 */
#define SENDFILE_BUF_SIZE   (512ULL * 1024 * 1024)

/*=============================================================================
 *  服务端入口
 *  
 *  功能：
 *  1. 在 fullsync_port 上监听 TCP 连接
 *  2. 接受客户端连接
 *  3. 将 token（快照 offset）作为流头发送
 *  4. 通过 sendfile 零拷贝发送 RDB 快照数据
 *  
 *  @param token 上层会话元数据（全量同步中 = 快照 offset）
 *  @return 0 成功，-1 失败
 *
 *  调用者：repl_fullsync_master_trigger 中 fork 的子进程
 *
 *  实现要点：
 *  - 使用 sendfile 避免用户态到内核态的数据拷贝
 *  - sendfile 可能只部分返回，循环发送直到发完（大 RDB/跨机必需）
 *  - 流程：等客户端 ready 信号 → SAVE 落盘 → 发 token → 发 size → 发数据
 *  - 计时：xfer 只夹 sendfile 循环（纯传输），落盘耗时单列 save=
 */
int sendfile_server_run(uint64_t token);

/*=============================================================================
 *  客户端入口
 *  
 *  功能：
 *  1. 连接服务端的 fullsync_port（带重试，等服务端监听就绪）
 *  2. 发 ready 信号 → 接收流头 token(8B) + size(8B)
 *  3. 接收 RDB 快照数据到大块内存缓冲，就地 rdb_load_from_buf 加载
 *
 *  @param out_token 输出：从流头解出的 token（快照 offset）
 *  @return 0 成功，-1 失败
 *
 *  调用者：repl_fullsync_slave_start
 *
 *  实现要点：
 *  - 流头顺序：token(8B) → size(8B) → 数据；线上格式与落盘版完全一致
 *    （磁盘格式，带 crc 槽），只是不再经 /tmp 中转
 *  - 接收缓冲 = SENDFILE_BUF_SIZE，malloc + 触页：把缺页代价挪到传输窗口
 *    之外（RDMA 侧是 rdma_reg_write，同理）。不用大页 —— 实测无额外贡献，
 *    预触才是那个关键动作
 *  - 触页排在发 ready 之后：服务端收到 ready 即开始 SAVE（秒级），
 *    从端触页正好藏在这段时间里，两端计时字段都不受影响
 *  - connect 重试 30 次 × 200ms：服务端 fork 子进程起监听有延迟
 *  - 计时：接收端只报 [sendfile] recv-end（字节数 + 墙钟），不出速率——
 *    这段等待里夹着本端 copy_to_user 的耗时，速率一律以发送端为准
 */
int sendfile_client_run(uint64_t *out_token);

#endif /* __SENDFILE_H__ */