/*=============================================================================
 *  repl_fullsync.h — 全量同步编排（传输无关）
 *
 *  功能：管理主从复制中的全量同步（Full Sync）流程
 *
 *  设计原则：
 *  1. 传输无关：具体传输方式（sendfile/RDMA）由内部按配置分派
 *  2. 上层逻辑：fork 传输子进程、PSYNC +FULLRESYNC 触发、从库全量流程
 *  3. 子进程回收：全局 SIGCHLD handler 回收（无派发框架）
 *  4. 与增量模块配合：全量同步后记录快照偏移，增量模块据此续传
 *============================================================================*/

#ifndef __REPL_FULLSYNC_H__
#define __REPL_FULLSYNC_H__

#include <stddef.h>

/*=============================================================================
 *  常量定义
 *============================================================================*/

/*=============================================================================
 *  全局状态
 *============================================================================*/

/**
 * 全量同步快照偏移量（数据面 → 控制面的权威续传 offset）
 *
 * 全量传输在流头带出的会话 token（全量同步里 = 快照 offset）
 * Slave 加载完快照后由 repl_fullsync_slave_start 写入
 * 增量模块（repl_incr_slave）据此从该偏移量续传
 *
 * 值语义：
 * - 0：尚未完成全量同步
 * - >0：快照对应的 Master 偏移量
 *
 * 交接契约：本 token 是续传 offset 的唯一权威。+FULLRESYNC 控制面回复不带
 * offset（从库只做前缀匹配），offset 只经数据面流头这一份拷贝传递
 * （master 侧说明见 repl_incr_master.c 的 master_start_fullsync）。
 */
extern size_t g_repl_snapshot_offset;

/*=============================================================================
 *  公开 API
 *============================================================================*/

/**
 * 触发 Master 全量同步（PSYNC 握手判定 +FULLRESYNC 时）
 *
 * 功能：
 * 1. 清理上一轮残留子进程（kill + waitpid）
 * 2. fork 传输子进程，内部按配置分派 sendfile / RDMA 发送 RDB 快照
 *
 * 调用时机：PSYNC 握手 offset 过期回 +FULLRESYNC 时
 *
 * @return 0 成功，-1 失败
 *
 * 限制：
 * - 同时只运行一个全量同步传输子进程
 * - 子进程回收：全局 SIGCHLD handler
 */
int repl_fullsync_master_trigger(void);

/**
 * 从库全量同步
 *
 * 功能：
 * 1. 连接 Master 数据面端口（sendfile/RDMA）
 * 2. 接收 RDB 快照数据
 * 3. 加载快照到本地字典
 * 4. 记录快照偏移量（g_repl_snapshot_offset）
 * 5. 返回给增量模块续传
 *
 * 调用时机：Slave 收到 PSYNC 握手 +FULLRESYNC 后
 *
 * @return 0 成功，-1 失败
 *
 * 注意：
 * - 阻塞操作，由事件循环 tick 驱动
 * - 加载期间设置 g_in_reload = 1（抑制日志和复制）
 */
int repl_fullsync_slave_start(void);

#endif /* __REPL_FULLSYNC_H__ */
